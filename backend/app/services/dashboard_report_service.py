"""
Excel report generation for the Dashboard (W11-03 reporting).

Companion to the PDF export: where the PDF is a visual snapshot of the
dashboard, this workbook carries the numbers behind it so they can be
re-sorted, pivoted and charted by hand.

Workbook layout:
  Sheet "Dashboard"  — cover block, the six KPI cards as label/value rows,
    a per-lab-group budget-vs-spend table, and a native Excel bar chart
    drawn from that table (a real chart, not a picture, so it stays live).
  Sheet "Budget Breakdown" — the drilldown table flattened to one row per
    Lab Group / Lab / Category, carrying all six metrics at every level.
  Sheet "Monthly Trend" — approved spend per month with a native line chart.

Uses only openpyxl, already a dependency.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from decimal import Decimal, InvalidOperation
from io import BytesIO
from typing import Any, Sequence

from openpyxl import Workbook
from openpyxl.chart import BarChart, LineChart, Reference
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.worksheet import Worksheet

from app.services.excel_style import (
    AMBER,
    BLUE,
    BLUE_TINT,
    BOX_BORDER,
    GREY_TINT,
    MONEY_FMT,
    MUTED_TEXT,
    NAVY,
    PERCENT_FMT,
    RED,
    write_cover,
    write_table_header,
)

# Utilisation bands, mirroring the dashboard's KPI card colouring.
CRITICAL_PCT = 95.0
WARNING_PCT = 80.0


@dataclass
class DashboardMeta:
    """Cover-block context: who exported this, and under which filters."""

    generated_at: datetime
    generated_by_name: str
    generated_by_email: str
    role_label: str
    scope_label: str
    fy_label: str
    date_range_label: str
    lab_group_label: str
    lab_label: str


@dataclass
class DashboardKpis:
    """The six cards along the top of the dashboard."""

    total_budget: float
    actual_spend: float
    pending: float
    available_balance: float
    utilisation_pct: float
    projected_utilisation_pct: float


def build_dashboard_workbook(
    meta: DashboardMeta,
    kpis: DashboardKpis,
    lab_groups: Sequence[Any],
    breakdown_groups: Sequence[Any],
    monthly_points: Sequence[Any],
) -> BytesIO:
    """Render the dashboard report and return it as an in-memory .xlsx."""
    wb = Workbook()
    overview = wb.active
    overview.title = "Dashboard"
    _build_overview_sheet(overview, meta, kpis, breakdown_groups)

    _build_breakdown_sheet(wb.create_sheet("Budget Breakdown"), meta, breakdown_groups)
    _build_monthly_sheet(wb.create_sheet("Monthly Trend"), meta, monthly_points)

    stream = BytesIO()
    wb.save(stream)
    stream.seek(0)
    return stream


def _meta_rows(meta: DashboardMeta) -> list[tuple[str, str]]:
    return [
        ("Generated", meta.generated_at.strftime("%d %b %Y, %I:%M %p")),
        ("Generated by", f"{meta.generated_by_name} ({meta.generated_by_email})"),
        ("Role", meta.role_label),
        ("Scope", meta.scope_label),
        ("Fiscal Year", meta.fy_label),
        ("Date Range", meta.date_range_label),
        ("Lab Group Filter", meta.lab_group_label),
        ("Lab Filter", meta.lab_label),
    ]


# ─── Sheet 1: Dashboard overview ─────────────────────────────────────────
def _build_overview_sheet(
    ws: Worksheet,
    meta: DashboardMeta,
    kpis: DashboardKpis,
    groups: Sequence[Any],
) -> None:
    ncols = 6
    cursor = write_cover(ws, "Dashboard Report", _meta_rows(meta), ncols)

    # ── KPI block ────────────────────────────────────────────────────
    cursor += 1
    heading = ws.cell(row=cursor, column=1, value="Key Figures")
    heading.font = Font(bold=True, size=11, color=NAVY)
    ws.merge_cells(start_row=cursor, start_column=1, end_row=cursor, end_column=ncols)

    kpi_rows: list[tuple[str, float, str]] = [
        ("Total Budget", kpis.total_budget, MONEY_FMT),
        ("Actual Spend", kpis.actual_spend, MONEY_FMT),
        ("Pending Amount", kpis.pending, MONEY_FMT),
        ("Available Balance", kpis.available_balance, MONEY_FMT),
        ("Utilisation %", kpis.utilisation_pct, PERCENT_FMT),
        ("Projected Utilisation %", kpis.projected_utilisation_pct, PERCENT_FMT),
    ]
    for label, value, fmt in kpi_rows:
        cursor += 1
        label_cell = ws.cell(row=cursor, column=1, value=label)
        label_cell.font = Font(bold=True, size=10)
        label_cell.fill = PatternFill("solid", fgColor=GREY_TINT)
        label_cell.border = BOX_BORDER
        value_cell = ws.cell(row=cursor, column=2, value=value)
        value_cell.number_format = fmt
        value_cell.font = Font(size=10, bold=True, color=_kpi_colour(label, value))
        value_cell.alignment = Alignment(horizontal="right")
        value_cell.border = BOX_BORDER

    # ── Per-lab-group table, which also feeds the chart ──────────────
    cursor += 2
    table_heading = ws.cell(row=cursor, column=1, value="By Lab Group")
    table_heading.font = Font(bold=True, size=11, color=NAVY)
    ws.merge_cells(start_row=cursor, start_column=1, end_row=cursor, end_column=ncols)

    header_row = cursor + 1
    write_table_header(
        ws,
        header_row,
        [
            "Lab Group",
            "Budget",
            "Actual Spend",
            "Pending",
            "Available",
            "Utilisation %",
        ],
    )

    row = header_row
    for group in groups:
        row += 1
        util = float(group.utilisation_pct or 0)
        values: list[Any] = [
            group.lab_group_name,
            _num(group.budget_sgd),
            _num(group.actual_spend_sgd),
            _num(group.pending_sgd),
            _num(group.available_balance_sgd),
            util,
        ]
        for idx, value in enumerate(values, start=1):
            cell = ws.cell(row=row, column=idx, value=value)
            cell.font = Font(size=10)
            cell.border = BOX_BORDER
            if idx == 6:
                cell.number_format = PERCENT_FMT
                cell.font = Font(size=10, bold=True, color=_util_colour(util))
            elif idx > 1:
                cell.number_format = MONEY_FMT
            if idx > 1:
                cell.alignment = Alignment(horizontal="right")

    if not groups:
        row += 1
        note = ws.cell(
            row=row, column=1, value="No lab groups matched the selected filters."
        )
        note.font = Font(italic=True, size=10, color=MUTED_TEXT)
    else:
        _add_group_chart(ws, header_row, row, ncols)

    for idx, width in enumerate([30, 16, 16, 16, 16, 15], start=1):
        ws.column_dimensions[get_column_letter(idx)].width = width
    ws.sheet_view.showGridLines = False


def _add_group_chart(ws: Worksheet, header_row: int, last_row: int, ncols: int) -> None:
    """Native Excel bar chart of Budget vs Actual per lab group."""
    chart = BarChart()
    chart.type = "col"
    chart.title = "Budget vs Actual Spend by Lab Group"
    chart.y_axis.title = "SGD"
    chart.height = 9
    chart.width = 24
    chart.style = 10
    data = Reference(ws, min_col=2, max_col=3, min_row=header_row, max_row=last_row)
    cats = Reference(ws, min_col=1, min_row=header_row + 1, max_row=last_row)
    chart.add_data(data, titles_from_data=True)
    chart.set_categories(cats)
    ws.add_chart(chart, f"{get_column_letter(ncols + 2)}4")


# ─── Sheet 2: Budget Breakdown ───────────────────────────────────────────
def _build_breakdown_sheet(
    ws: Worksheet, meta: DashboardMeta, groups: Sequence[Any]
) -> None:
    ncols = 8
    cursor = write_cover(ws, "Budget Breakdown", _meta_rows(meta), ncols)

    header_row = cursor + 1
    write_table_header(
        ws,
        header_row,
        [
            "Level",
            "Lab Group",
            "Lab",
            "Category",
            "Budget",
            "Actual Spend",
            "Pending",
            "Utilisation %",
        ],
    )

    row = header_row
    for group in groups:
        row += 1
        _write_breakdown_row(
            ws,
            row,
            "Lab Group",
            group.lab_group_name,
            "",
            "",
            group,
            bold=True,
            fill=BLUE_TINT,
        )
        for lab in group.labs:
            row += 1
            _write_breakdown_row(
                ws,
                row,
                "Lab",
                group.lab_group_name,
                lab.lab_name,
                "",
                lab,
                fill=GREY_TINT,
            )
            for category in lab.categories:
                row += 1
                _write_breakdown_row(
                    ws,
                    row,
                    "Category",
                    group.lab_group_name,
                    lab.lab_name,
                    category.category_name,
                    category,
                )

    if row == header_row:
        row += 1
        note = ws.cell(
            row=row, column=1, value="No budget data matched the selected filters."
        )
        note.font = Font(italic=True, size=10, color=MUTED_TEXT)
    else:
        ws.auto_filter.ref = f"A{header_row}:{get_column_letter(ncols)}{row}"

    for idx, width in enumerate([12, 26, 28, 20, 15, 15, 14, 14], start=1):
        ws.column_dimensions[get_column_letter(idx)].width = width
    ws.freeze_panes = ws.cell(row=header_row + 1, column=1)
    ws.sheet_view.showGridLines = False


def _write_breakdown_row(
    ws: Worksheet,
    row: int,
    level: str,
    group_name: str,
    lab_name: str,
    category_name: str,
    metrics: Any,
    bold: bool = False,
    fill: str | None = None,
) -> None:
    util = float(metrics.utilisation_pct or 0)
    values: list[Any] = [
        level,
        group_name,
        lab_name,
        category_name,
        _num(metrics.budget_sgd),
        _num(metrics.actual_spend_sgd),
        _num(metrics.pending_sgd),
        util,
    ]
    for idx, value in enumerate(values, start=1):
        cell = ws.cell(row=row, column=idx, value=value)
        cell.border = BOX_BORDER
        cell.font = Font(size=10, bold=bold)
        if fill:
            cell.fill = PatternFill("solid", fgColor=fill)
        if idx == 8:
            cell.number_format = PERCENT_FMT
            cell.font = Font(size=10, bold=True, color=_util_colour(util))
            cell.alignment = Alignment(horizontal="right")
        elif idx >= 5:
            cell.number_format = MONEY_FMT
            cell.alignment = Alignment(horizontal="right")


# ─── Sheet 3: Monthly Trend ──────────────────────────────────────────────
def _build_monthly_sheet(
    ws: Worksheet, meta: DashboardMeta, points: Sequence[Any]
) -> None:
    ncols = 2
    cursor = write_cover(ws, "Monthly Spending Trend", _meta_rows(meta), ncols)

    header_row = cursor + 1
    write_table_header(ws, header_row, ["Month", "Approved Spend"])

    row = header_row
    for point in points:
        row += 1
        month_cell = ws.cell(row=row, column=1, value=point.month)
        month_cell.font = Font(size=10)
        month_cell.border = BOX_BORDER
        amount_cell = ws.cell(row=row, column=2, value=_num(point.amount))
        amount_cell.number_format = MONEY_FMT
        amount_cell.font = Font(size=10)
        amount_cell.alignment = Alignment(horizontal="right")
        amount_cell.border = BOX_BORDER

    if row == header_row:
        row += 1
        note = ws.cell(
            row=row, column=1, value="No approved spending in the selected window."
        )
        note.font = Font(italic=True, size=10, color=MUTED_TEXT)
    else:
        chart = LineChart()
        chart.title = "Approved Spend by Month"
        chart.y_axis.title = "SGD"
        chart.x_axis.title = "Month"
        chart.height = 9
        chart.width = 24
        chart.style = 12
        data = Reference(ws, min_col=2, min_row=header_row, max_row=row)
        cats = Reference(ws, min_col=1, min_row=header_row + 1, max_row=row)
        chart.add_data(data, titles_from_data=True)
        chart.set_categories(cats)
        ws.add_chart(chart, "D4")

    ws.column_dimensions["A"].width = 14
    ws.column_dimensions["B"].width = 18
    ws.sheet_view.showGridLines = False


# ─── Helpers ─────────────────────────────────────────────────────────────
def _num(raw: Any) -> float:
    if raw is None or raw == "":
        return 0.0
    try:
        return float(Decimal(str(raw)))
    except (InvalidOperation, ValueError):
        return 0.0


def _util_colour(pct: float) -> str:
    if pct >= CRITICAL_PCT:
        return RED
    if pct >= WARNING_PCT:
        return AMBER
    return NAVY


def _kpi_colour(label: str, value: float) -> str:
    if "Utilisation" in label:
        return _util_colour(value)
    if label == "Available Balance" and value < 0:
        return RED
    return BLUE if label == "Actual Spend" else NAVY
